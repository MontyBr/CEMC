// Chinese keyword -> English, the glossary read backwards ("川菜" -> "Sichuan").
const REVERSE_QUERY = {};
for (const [en, zh] of Object.entries(QUERY_GLOSSARY)) {
  REVERSE_QUERY[zh] ??= en.replace(/^./, (c) => c.toUpperCase());
}

function singular(word) {
  if (word.endsWith('ies')) return word.slice(0, -3) + 'y';
  if (word.endsWith('es') && /(sh|ch|x|ss)es$/.test(word)) return word.slice(0, -2);
  if (word.endsWith('s') && !word.endsWith('ss')) return word.slice(0, -1);
  return word;
}

const FILLER = /^(the |a |an |some |good |best |cheap |nearby |near me |near )+|( near me| nearby| near here| around here)$/g;

// Returns Chinese keywords for an English query, or null when the glossary
// has no match. Strings that already contain Chinese are passed through.
export function lookupQuery(query) {
  const raw = String(query || '').trim();
  if (!raw) return null;
  if (/[一-鿿]/.test(raw)) return raw;

  const q = raw.toLowerCase().replace(/\s+/g, ' ').replace(FILLER, '').trim();
  for (const candidate of [q, singular(q)]) {
    if (QUERY_GLOSSARY[candidate]) return QUERY_GLOSSARY[candidate];
  }
  return null;
}

// "餐饮服务;中餐厅;火锅店" (AMap) or "美食:火锅" (Tencent) -> "Hotpot",
// using the most specific segment we know.
export function translateType(type) {
  const segments = String(type || '').split(/[;|:]/).filter(Boolean);
  for (let i = segments.length - 1; i >= 0; i--) {
    const english = TYPE_GLOSSARY[segments[i]] || REVERSE_QUERY[segments[i]];
    if (english) return english;
  }
  return '';
}
